// Builds the website for search engines: writes the structured data (JSON-LD) into index.html and
// generates the Arabic page ar.html from it, translated with the AR strings in app.js.
// Run: node scripts/build-site.mjs   (Vercel runs it on every deploy)
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SITE_DIR = join(import.meta.dirname, '..', 'website')
const ORIGIN = 'https://downly-app.vercel.app'
const RELEASES = 'https://github.com/mo7ammed3adel/downly-releases/releases/latest'

const read = (name) => readFileSync(join(SITE_DIR, name), 'utf8')

// The AR object literal in app.js is plain data, so it can be evaluated on its own
const appJs = read('app.js')
const arSource = /const AR = (\{[\s\S]*?\n\})/.exec(appJs)?.[1]
if (!arSource) throw new Error('AR strings not found in app.js')
const AR = new Function(`return ${arSource}`)()

const decode = (html) =>
  html
    .replace(/<[^>]+>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim()
const encode = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

// Every element with data-i18n and its English text
const I18N_ELEMENT = /(<(\w+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2\s*>)/g
function englishStrings(html) {
  const en = {}
  for (const [, , , key, inner] of html.matchAll(I18N_ELEMENT)) en[key] = decode(inner)
  return en
}

const HEAD = {
  en: {
    description:
      'Downly is a free download manager for Windows, macOS, Linux and Android: up to 32× faster multi-connection downloads, YouTube and social media videos, MP3 audio, playlists and Spotify songs. No ads, no limits.'
  },
  ar: {
    title: 'Downly — برنامج تحميل مجاني للفيديوهات والأغاني والملفات | بديل IDM',
    description:
      'Downly برنامج تحميل مجاني للويندوز والماك ولينكس والأندرويد: تحميل أسرع لحد 32 مرة، فيديوهات يوتيوب والسوشيال ميديا، صوت MP3، قوايم تشغيل كاملة وأغاني سبوتيفاي. من غير إعلانات ولا حدود.',
    ogTitle: 'Downly — برنامج تحميل مجاني',
    ogDescription: 'تحميل أسرع، فيديوهات، أغاني وقوايم تشغيل. مجاني ومن غير إعلانات.'
  }
}

function schema(lang, strings) {
  const url = lang === 'ar' ? `${ORIGIN}/ar` : `${ORIGIN}/`
  const features = ['f1', 'f2', 'f3', 'f4', 'f5', 'f6', 'f7', 'f9', 'f8'].map((k) => `${strings[`${k}.t`]}: ${strings[`${k}.d`]}`)
  const faq = Object.keys(strings)
    .filter((k) => /^q\d+$/.test(k) && strings[`a${k.slice(1)}`])
    .map((k) => ({
      '@type': 'Question',
      name: strings[k],
      acceptedAnswer: { '@type': 'Answer', text: strings[`a${k.slice(1)}`] }
    }))
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'WebSite',
        '@id': `${ORIGIN}/#website`,
        url: `${ORIGIN}/`,
        name: 'Downly',
        inLanguage: ['en', 'ar']
      },
      {
        '@type': 'SoftwareApplication',
        '@id': `${ORIGIN}/#app`,
        name: 'Downly',
        url,
        inLanguage: lang,
        description: HEAD[lang].description,
        applicationCategory: 'UtilitiesApplication',
        applicationSubCategory: 'Download manager',
        operatingSystem: 'Windows 11, Windows 10, Windows 8, Windows 7, macOS, Linux, Android',
        downloadUrl: RELEASES,
        installUrl: 'https://apps.microsoft.com/detail/9N3LXLPF25K4',
        image: `${ORIGIN}/assets/icon.png`,
        screenshot: `${ORIGIN}/assets/og.png`,
        isAccessibleForFree: true,
        offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
        featureList: features,
        sameAs: [
          'https://apps.microsoft.com/detail/9N3LXLPF25K4',
          'https://microsoftedge.microsoft.com/addons/detail/edoonifkeddgpamlhadfbagimigcaena'
        ],
        author: { '@type': 'Person', name: 'Mohamed Adel', url: 'https://github.com/mo7ammed3adel' }
      },
      { '@type': 'FAQPage', '@id': `${url}#faq`, url, inLanguage: lang, mainEntity: faq }
    ]
  }
}

function withSchema(html, lang, strings) {
  const json = JSON.stringify(schema(lang, strings), null, 2).replace(/</g, '\\u003c').replace(/\n/g, '\n    ')
  const block = `<!-- schema:start (generated by scripts/build-site.mjs) -->\n    <script type="application/ld+json">\n    ${json}\n    </script>\n    <!-- schema:end -->`
  const out = html.replace(/<!-- schema:start[\s\S]*?<!-- schema:end -->/, block)
  if (out === html && !html.includes(block)) throw new Error('schema markers missing in index.html')
  return out
}

// Swaps one exact string, failing loudly if index.html changed and it no longer matches
function swap(html, from, to) {
  if (!html.includes(from)) throw new Error(`not found in index.html: ${from}`)
  return html.split(from).join(to)
}

const indexHtml = read('index.html')
const en = englishStrings(indexHtml)
writeFileSync(join(SITE_DIR, 'index.html'), withSchema(indexHtml, 'en', en))

let ar = indexHtml.replace(I18N_ELEMENT, (all, open, tag, key, inner, close) => (AR[key] ? open + encode(AR[key]) + close : all))
const h = HEAD.ar
ar = swap(ar, '<html lang="en" dir="ltr">', '<html lang="ar" dir="rtl">')
ar = swap(ar, '<title>Downly — Free Download Manager &amp; IDM Alternative</title>', `<title>${encode(h.title)}</title>`)
ar = swap(ar, `content="${HEAD.en.description}"`, `content="${h.description}"`)
ar = swap(ar, '<link rel="canonical" href="https://downly-app.vercel.app/" />', '<link rel="canonical" href="https://downly-app.vercel.app/ar" />')
ar = swap(ar, '<meta property="og:url" content="https://downly-app.vercel.app/" />', '<meta property="og:url" content="https://downly-app.vercel.app/ar" />')
ar = swap(ar, '<meta property="og:locale" content="en_US" />', '<meta property="og:locale" content="ar_EG" />')
ar = swap(ar, '<meta property="og:locale:alternate" content="ar_EG" />', '<meta property="og:locale:alternate" content="en_US" />')
ar = swap(ar, 'content="Downly — Free download manager"', `content="${h.ogTitle}"`)
ar = swap(ar, 'content="Faster downloads, videos, music and playlists. Free, no ads."', `content="${h.ogDescription}"`)
ar = swap(ar, '<a id="lang" class="btn ghost small" href="/ar" hreflang="ar" lang="ar">عربي</a>', '<a id="lang" class="btn ghost small" href="/" hreflang="en" lang="en">English</a>')
ar = withSchema(ar, 'ar', { ...en, ...AR })
writeFileSync(join(SITE_DIR, 'ar.html'), ar)

console.log('website: index.html schema updated, ar.html written')
